const std = @import("std");
const parser = @import("parser");
const decoder = @import("estree/decoder.zig");
const emit = @import("estree/emit.zig");

pub fn main(init: std.process.Init) !void {
    try emit.toStdout(init.io, generate);
}

fn generate(w: *std.Io.Writer) std.Io.Writer.Error!void {
    @setEvalBranchQuota(50_000);
    try w.writeAll(
        \\// generated by tools/gen_token_types.zig, do not edit
        \\
        \\/** Every token kind by name. Values may change between versions, compare by name. */
        \\export interface TokenKindMap {
        \\
    );
    const info = @typeInfo(parser.ast.TokenTag).@"enum";
    inline for (info.field_names, info.field_values) |name, value| {
        try w.print("  readonly {s}: {d};\n", .{ comptime decoder.tokenName(name), value });
    }
    try w.writeAll("}\n");
}
